// Social Icons Component
interface SocialIconsProps {
  config?: SocialMediaConfig
  size?: number
  className?: string
  showLabel?: boolean
}

export default function SocialIcons({ config, size = 20, className = '', showLabel = false }: SocialIconsProps) {
  const socialConfig = config || defaultSocialConfig
  
  const enabledPlatforms = socialConfig.platforms.filter(p => p.enabled)

  return (
    <div className={`flex flex-wrap gap-4 ${className}`}>
      {enabledPlatforms.map((platform) => (
        <a
          key={platform.id}
          href={platform.url}
          target="_blank"
          rel="noopener noreferrer"
          className="flex items-center gap-2 group"
          aria-label={platform.name}
        >
          <span 
            className="flex items-center justify-center w-9 h-9 rounded-full transition-all duration-300 group-hover:scale-110"
            style={{ 
              backgroundColor: `${platform.color}20`,
              color: platform.color 
            }}
          >
            <SocialIcon platform={platform} size={size} />
          </span>
          {showLabel && (
            <span className="text-sm text-gray-400 group-hover:text-white transition-colors">
              {platform.name}
            </span>
          )}
        </a>
      ))}
      
      {/* WhatsApp Business Button */}
      {socialConfig.businessWhatsapp && (
        <a
          href={`https://wa.me/${socialConfig.businessWhatsapp.replace(/\D/g, '')}`}
          target="_blank"
          rel="noopener noreferrer"
          className="flex items-center gap-2 group"
          aria-label="WhatsApp Business"
        >
          <span 
            className="flex items-center justify-center w-9 h-9 rounded-full bg-[#25D366]/20 text-[#25D366] transition-all duration-300 group-hover:scale-110"
          >
            <SocialIcon 
              platform={{ id: 'whatsapp', name: 'WhatsApp', icon: 'whatsapp', url: '', color: '#25D366', enabled: true }} 
              size={size} 
            />
          </span>
          {showLabel && (
            <span className="text-sm text-gray-400 group-hover:text-white transition-colors">
              WhatsApp
            </span>
          )}
        </a>
      )}
    </div>
  )
}

